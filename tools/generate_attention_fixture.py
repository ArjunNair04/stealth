"""Independent double equations for multihead attention and a pre-norm block."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

W, H, F, N = 4, 2, 7, 4
EPS = struct.unpack('<f', struct.pack('<f', 1e-5))[0]


def fp32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def pattern(n, seed, divisor=32):
    return [fp32(((i * 13 + seed) % 29 - 14) / divisor) for i in range(n)]


def dense(x, weight, bias):
    return [math.fsum(a * b for a, b in zip(x, weight[o * len(x):(o + 1) * len(x)])) + v
            for o, v in enumerate(bias)]


def norm(x, scale, shift):
    mean = math.fsum(x) / len(x)
    variance = math.fsum((a - mean) ** 2 for a in x) / len(x)
    return [(a - mean) / math.sqrt(variance + EPS) * g + b for a, g, b in zip(x, scale, shift)]


def attention(q, k, v, heads):
    width, count = len(q[0]), len(q)
    d = width // heads
    result = [[0.] * width for _ in q]
    for t in range(count):
        for h in range(heads):
            channels = range(h * d, (h + 1) * d)
            scores = [math.fsum(q[t][c] * k[j][c] for c in channels) / math.sqrt(d) for j in range(t + 1)]
            weights = [math.exp(s - max(scores)) for s in scores]
            total = math.fsum(weights)
            for c in channels:
                result[t][c] = math.fsum(p / total * v[j][c] for j, p in enumerate(weights))
    return result


def rows(flat, width=W):
    return [flat[i:i + width] for i in range(0, len(flat), width)]


def flatten(matrix):
    return [v for row in matrix for v in row]


def generate():
    p = {
        'attn_scale': [1., .75, 1.25, -.5], 'attn_shift': pattern(W, 1, 64),
        'qkv_weights': pattern(3 * W * W, 7), 'qkv_bias': pattern(3 * W, 3, 64),
        'projection_weights': pattern(W * W, 11), 'projection_bias': pattern(W, 13, 64),
        'ff_scale': [.5, 1., -.75, 1.25], 'ff_shift': pattern(W, 5, 64),
        'up_weights': pattern(F * W, 17), 'up_bias': pattern(F, 19, 64),
        'down_weights': pattern(W * F, 23), 'down_bias': pattern(W, 2, 64),
        'input': pattern(N * W, 11, 8), 'input_other': pattern(N * W, 3, 8),
    }
    for suffix in ['', '_other']:
        x = rows(p['input' + suffix])
        normalized = [norm(row, p['attn_scale'], p['attn_shift']) for row in x]
        projected = [dense(row, p['qkv_weights'], p['qkv_bias']) for row in normalized]
        q, k, v = ([row[i * W:(i + 1) * W] for row in projected] for i in range(3))
        context = attention(q, k, v, H)
        residual = [[a + b for a, b in zip(row, dense(ctx, p['projection_weights'], p['projection_bias']))]
                    for row, ctx in zip(x, context)]
        result = []
        for row in residual:
            z = norm(row, p['ff_scale'], p['ff_shift'])
            up = dense(z, p['up_weights'], p['up_bias'])
            activated = [.5 * a * math.erfc(-a / math.sqrt(2)) for a in up]
            down = dense(activated, p['down_weights'], p['down_bias'])
            result.append([a + b for a, b in zip(row, down)])
        p['expected' + suffix] = flatten(result)
        if not suffix:
            p.update(query=flatten(q), key=flatten(k), value=flatten(v), context=flatten(context))
    lines = ['// Generated by independent equations; never bless native outputs.', '#pragma once',
             '#include <array>', 'namespace attention_fixture {',
             f'inline constexpr std::size_t width={W}, heads={H}, hidden={F}, tokens={N};',
             'inline constexpr float epsilon=1e-5F;']
    for name, values in p.items():
        literals = ', '.join(format(x, '.10e') + 'F' for x in values)
        lines.append(f'inline constexpr std::array<float, {len(values)}> {name}' + '{' + literals + '};')
    lines.append('} // namespace attention_fixture')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / 'tests/fixtures/attention.hpp'
    content = generate()
    metadata = {
        'schema_version': 1,
        'generator_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'fixture_sha256': hashlib.sha256(content.encode()).hexdigest(),
        'dimensions': {'tokens': N, 'width': W, 'heads': H, 'hidden': F},
        'reference': 'Independent Python standard-library double equations (math.fsum/exp/erfc); not PyTorch',
        'attention_tolerance': {'absolute': 2e-5, 'relative': 5e-5},
        'block_tolerance': {'absolute': 3e-5, 'relative': 1e-4},
        'purpose': 'Untrained diagnostic weights only; no prediction or financial evidence',
    }
    if args.check:
        if path.read_text() != content or json.loads(path.with_suffix('.json').read_text()) != metadata:
            raise SystemExit('Fixture/provenance mismatch: investigate before changing expected answers')
        print('Attention fixture and provenance reproduced exactly')
    else:
        path.write_text(content)
        path.with_suffix('.json').write_text(json.dumps(metadata, indent=2) + '\n')


if __name__ == '__main__':
    main()
