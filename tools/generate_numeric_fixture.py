"""Independent double-precision feed-forward fixture; Python standard library only."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct


def fp32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


def generate():
    width, hidden = 4, 7
    fields = {
        'scale': [1.0, 0.75, 1.25, -0.5],
        'shift': [0.1, -0.2, 0.3, -0.4],
        'up_weights': [((i * 37 + 11) % 29 - 14) / 32 for i in range(width * hidden)],
        'up_bias': [((i * 11 + 3) % 9 - 4) / 16 for i in range(hidden)],
        'down_weights': [((i * 13 + 7) % 23 - 11) / 32 for i in range(width * hidden)],
        'down_bias': [((i * 7 + 1) % 9 - 4) / 16 for i in range(width)],
        'input': [1.5, -0.25, 0.5, 2.0],
        'input_other': [-1.0, 2.0, 0.25, -0.75],
        'input_constant': [2.0] * width,
    }
    fields = {key: [fp32(value) for value in values] for key, values in fields.items()}
    epsilon = fp32(1e-5)

    def predict(x):
        mean = math.fsum(x) / width
        variance = math.fsum((v - mean) ** 2 for v in x) / width
        normalized = [(v - mean) / math.sqrt(variance + epsilon) * scale + shift
                      for v, scale, shift in zip(x, fields['scale'], fields['shift'])]
        expanded = [math.fsum(w * v for w, v in zip(fields['up_weights'][j * width:(j + 1) * width], normalized))
                    + fields['up_bias'][j] for j in range(hidden)]
        activated = [v * 0.5 * math.erfc(-v / math.sqrt(2)) for v in expanded]
        projected = [math.fsum(w * v for w, v in zip(fields['down_weights'][j * hidden:(j + 1) * hidden], activated))
                     + fields['down_bias'][j] for j in range(width)]
        return [a + b for a, b in zip(x, projected)]

    # These are equations, not calls to the native engine or its implementation.
    for suffix in ['', '_other', '_constant']:
        fields['expected' + suffix] = predict(fields['input' + suffix])
    lines = ['// Generated by tools/generate_numeric_fixture.py; do not bless native outputs.',
             '#pragma once', '#include <array>', 'namespace fixture {',
             'inline constexpr std::size_t width = 4;', 'inline constexpr std::size_t hidden = 7;',
             'inline constexpr float epsilon = 1e-5F;']
    for name, values in fields.items():
        literals = ', '.join(format(value, '.10e') + 'F' for value in values)
        lines.append(f'inline constexpr std::array<float, {len(values)}> {name}' + '{' + literals + '};')
    lines.append('} // namespace fixture')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=Path('tests/fixtures/feed_forward.hpp'))
    args = parser.parse_args()
    content = generate()
    if args.check:
        if args.output.read_text() != content:
            raise SystemExit('Fixture differs: inspect the generator/environment before changing it')
        metadata = json.loads(args.output.with_suffix('.json').read_text())
        if metadata['generator_sha256'] != hashlib.sha256(Path(__file__).read_bytes()).hexdigest():
            raise SystemExit('Generator hash differs from fixture provenance')
        if metadata['fixture_sha256'] != hashlib.sha256(content.encode()).hexdigest():
            raise SystemExit('Fixture hash differs from provenance')
        print('Independent fixture and provenance reproduced exactly')
    else:
        args.output.write_text(content)
        metadata = {
            'schema_version': 1,
            'generator_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'fixture_sha256': hashlib.sha256(content.encode()).hexdigest(),
            'reference': 'Python standard library, double precision math.fsum/erfc, deterministic explicit parameters',
            'dimensions': {'width': 4, 'hidden': 7},
            'tolerances': {'absolute': 2e-5, 'relative': 5e-5},
            'purpose': 'Numerical integration evidence only; no trained model or financial data',
        }
        args.output.with_suffix('.json').write_text(json.dumps(metadata, indent=2) + '\n')


if __name__ == '__main__':
    main()
